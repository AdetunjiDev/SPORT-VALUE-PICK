function json(
  res: http.ServerResponse,
  status: number,
  body: unknown,
  extraHeaders?: Record<string, string>,
): void {
  res.writeHead(status, {
    "Content-Type": "application/json; charset=utf-8",
    ...CORS,
    ...(extraHeaders ?? {}),
  });
  res.end(JSON.stringify(body));
}

function readBody(req: http.IncomingMessage, maxBytes = 256 * 1024): Promise<string> {
  return new Promise((resolve, reject) => {
    let size = 0;
    const chunks: Buffer[] = [];
    req.on("data", (c: Buffer) => {
      size += c.length;
      if (size > maxBytes) {
        reject(new Error("payload too large"));
        req.destroy();
        return;
      }
      chunks.push(c);
    });
    req.on("end", () => resolve(Buffer.concat(chunks).toString("utf8")));
    req.on("error", reject);
  });
}

function extractApiKey(req: http.IncomingMessage): string | null {
  const auth = req.headers.authorization;
  if (typeof auth === "string") {
    const m = /^Bearer\s+(.+)$/i.exec(auth.trim());
    if (m) return m[1].trim();
  }
  const hdr = req.headers["x-api-key"];
  if (typeof hdr === "string" && hdr.trim()) return hdr.trim();
  return null;
}

function authorized(req: http.IncomingMessage): boolean {
  const key = extractApiKey(req);
  return !!key && key === CHATGPT_API_KEY;
}

function walletFrom(
  req: http.IncomingMessage,
  body?: { walletId?: string },
  query?: URLSearchParams,
): { owner: string; walletId: string; created: boolean } {
  const fromHdr =
    typeof req.headers["x-wallet-id"] === "string"
      ? req.headers["x-wallet-id"].trim()
      : "";
  const fromBody = String(body?.walletId ?? "").trim();
  const fromQ = query?.get("walletId")?.trim() ?? "";
  let id = fromHdr || fromBody || fromQ;
  let created = false;
  if (!id || !/^[a-f0-9]{16,64}$/i.test(id)) {
    id = randomBytes(16).toString("hex");
    created = true;
  }
  return { owner: `gpt:${id.toLowerCase()}`, walletId: id.toLowerCase(), created };
}

function validGameType(v: unknown): GameType {
  const s = String(v ?? "result");
  const ok = ["result", "goals", "btts", "safe", "both"] as const;
  return (ok as readonly string[]).includes(s) ? (s as GameType) : "result";
}

